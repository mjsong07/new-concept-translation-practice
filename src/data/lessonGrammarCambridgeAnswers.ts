function lessonUnits(lesson: number): number[] {
  if (ODD_LESSON_UNITS[lesson]) return ODD_LESSON_UNITS[lesson];
  const prev = lesson - 1;
  return ODD_LESSON_UNITS[prev] || [];
}

export function lessonGrammarCambridgeAnswerPages(lesson: number): string[] {
  const pages = new Set<number>();
  for (const unit of lessonUnits(lesson)) {
    for (const p of UNIT_PAGES[unit] || []) pages.add(p);
  }
  return [...pages].sort((a, b) => a - b).map((p) => URL_BY_PAGE[p]).filter(Boolean);
}
