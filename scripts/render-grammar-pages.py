summary = {}
for n in range(1, 145):
    d = OUT / str(n)
    d.mkdir()
    # 问题页：整页渲染
    start = START[n]
    end = START[n + 1] if n + 1 in START else NEXT_KEY
    seq = 0
    for printed in range(start, end):
        idx = printed + OFFSET
        if idx >= doc.page_count:
            break
        seq += 1
        pix = doc[idx].get_pixmap(matrix=matrix, alpha=False)
        pix.save(str(d / f"page-{seq}.png"))

    # 答案区：本课标题到下一课标题之间的区域，按段裁剪
    page_n, top_n = ANSWER_HEADINGS[n]
    if n + 1 in ANSWER_HEADINGS:
        page_next, top_next = ANSWER_HEADINGS[n + 1]
    else:
        page_next, top_next = None, None
    segments = []
    if page_next == page_n:
        segments.append((page_n, top_n - PAD, top_next - PAD))
    else:
        segments.append((page_n, top_n - PAD, BOTTOM))
        if page_next is not None:
            for p in range(page_n + 1, page_next):
                segments.append((p, TOP_MARGIN, BOTTOM))
            if top_next >= SKIP_TOP:
                segments.append((page_next, TOP_MARGIN, top_next - PAD))
        else:
            for p in range(page_n + 1, ANSWER_END_PAGE + 1):
                segments.append((p, TOP_MARGIN, BOTTOM))
    aseq = 0
    for p, y0, y1 in segments:
        if y1 - y0 < 8:
            continue
        aseq += 1
        clip = pymupdf.Rect(0, y0, doc[p].rect.width, y1)
        pix = doc[p].get_pixmap(matrix=matrix, alpha=False, clip=clip)
        pix.save(str(d / f"answer-{aseq}.png"))
    if seq or aseq:
        summary[n] = (seq, aseq)

